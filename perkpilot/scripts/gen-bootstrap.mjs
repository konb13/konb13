// Concatenates every migration (in order) + the generated seed into a single
// supabase/bootstrap.sql you can paste into the Supabase SQL editor in one go.
// Run: node scripts/gen-bootstrap.mjs   (run gen-seed.ts first if catalog changed)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const base = new URL('../supabase/', import.meta.url).pathname;
const migDir = base + 'migrations/';

const migrations = readdirSync(migDir).filter((f) => f.endsWith('.sql')).sort();
const parts = ['-- AUTO-GENERATED by scripts/gen-bootstrap.mjs — full PerkPilot backend.', ''];

for (const file of migrations) {
  parts.push(`-- ============================================================`);
  parts.push(`-- migrations/${file}`);
  parts.push(`-- ============================================================`);
  parts.push(readFileSync(migDir + file, 'utf8').trimEnd(), '');
}

parts.push('-- ============================================================');
parts.push('-- seed.sql (global catalog + program_reference)');
parts.push('-- ============================================================');
parts.push(readFileSync(base + 'seed.sql', 'utf8').trimEnd(), '');

writeFileSync(base + 'bootstrap.sql', parts.join('\n'));
console.log(`Wrote supabase/bootstrap.sql from ${migrations.length} migrations + seed`);
